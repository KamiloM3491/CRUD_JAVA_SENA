    private void btnIniciarSesionActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnIniciarSesionActionPerformed
        // 1. Obtener los datos ingresados
        String correo = txtCorreoLogin.getText().trim();

        String contrasena = new String(
                txtContrasenaLogin.getPassword()
        );

        // 2. Crear el servicio de autenticacion
        com.mycompany.crud_java_sena.service.AutenticacionService servicio =
                new com.mycompany.crud_java_sena.service.AutenticacionService();

        // 3. Validar las credenciales
        com.mycompany.crud_java_sena.model.Usuario usuario =
                servicio.iniciarSesion(correo, contrasena);

        // 4. Comprobar el resultado
        if (usuario != null) {

            // Mostrar mensaje de bienvenida
            javax.swing.JOptionPane.showMessageDialog(
                    this,
                    "¡Bienvenido, " + usuario.getNombre()
                            + " " + usuario.getApellido() + "!",
                    "Inicio de sesión exitoso",
                    javax.swing.JOptionPane.INFORMATION_MESSAGE
            );

            // Abrir el perfil con los datos del usuario
            PerfilUsuario perfil = new PerfilUsuario(usuario);

            perfil.setLocationRelativeTo(null);
            perfil.setVisible(true);

            // Cerrar la ventana de Login
            this.dispose();

        } else {

            // Mostrar mensaje de error
            javax.swing.JOptionPane.showMessageDialog(
                    this,
                    "Correo electrónico o contraseña incorrectos.\n"
                            + "Verifica tus datos e intenta nuevamente.",
                    "Error de autenticación",
                    javax.swing.JOptionPane.WARNING_MESSAGE
            );

            // Limpiar el campo de contraseña
            txtContrasenaLogin.setText("");
            txtContrasenaLogin.requestFocus();
        }
    }//GEN-LAST:event_btnIniciarSesionActionPerformed


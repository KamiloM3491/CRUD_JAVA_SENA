    private void btnRegistrarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnRegistrarActionPerformed
        // Obtener los datos del formulario
        String nombre = txtNombre.getText().trim();
        String apellido = txtApellido.getText().trim();
        String correo = txtCorreo.getText().trim();
        String contrasena = new String(txtContrasena.getPassword());
        String telefono = txtTelefono.getText().trim();
        String direccion = txtDireccion.getText().trim();

        // Crear el objeto Usuario
        com.mycompany.crud_java_sena.model.Usuario usuario =
                new com.mycompany.crud_java_sena.model.Usuario();

        usuario.setNombre(nombre);
        usuario.setApellido(apellido);
        usuario.setCorreo(correo);
        usuario.setContrasena(contrasena);
        usuario.setTelefono(telefono);
        usuario.setDireccion(direccion);

        // Crear el servicio de autenticacion
        com.mycompany.crud_java_sena.service.AutenticacionService servicio =
                new com.mycompany.crud_java_sena.service.AutenticacionService();

        // Ejecutar el registro
        String resultado = servicio.registrarUsuario(usuario);

        // Comprobar el resultado
        if (resultado.equals("Usuario registrado correctamente.")) {

            javax.swing.JOptionPane.showMessageDialog(
                    this,
                    resultado,
                    "Registro exitoso",
                    javax.swing.JOptionPane.INFORMATION_MESSAGE
            );

            // Abrir la interfaz de Login
            Login login = new Login();

            login.setLocationRelativeTo(null);
            login.setVisible(true);

            // Cerrar la interfaz de registro
            this.dispose();

        } else {

            javax.swing.JOptionPane.showMessageDialog(
                    this,
                    resultado,
                    "Error en el registro",
                    javax.swing.JOptionPane.WARNING_MESSAGE
            );
        }
    }//GEN-LAST:event_btnRegistrarActionPerformed


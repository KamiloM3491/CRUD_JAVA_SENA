    private void btnActualizarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnActualizarActionPerformed
        // Obtener los datos modificados en el formulario
        String nombre = txtNombrePerfil.getText().trim();
        String apellido = txtApellidoPerfil.getText().trim();
        String telefono = txtTelefonoPerfil.getText().trim();
        String direccion = txtDireccionPerfil.getText().trim();

        // Verificar que exista un usuario autenticado
        if (usuarioActual == null) {

            javax.swing.JOptionPane.showMessageDialog(
                    this,
                    "No se encontró el usuario autenticado.",
                    "Error",
                    javax.swing.JOptionPane.ERROR_MESSAGE
            );

            return;
        }

        // Crear el servicio de autenticacion
        com.mycompany.crud_java_sena.service.AutenticacionService servicio =
                new com.mycompany.crud_java_sena.service.AutenticacionService();

        // Ejecutar la actualizacion del perfil
        String resultado = servicio.actualizarPerfil(
                usuarioActual,
                nombre,
                apellido,
                telefono,
                direccion
        );

        // Comprobar el resultado
        if (resultado.equals(
                "Los datos del perfil se actualizaron correctamente.")) {

            javax.swing.JOptionPane.showMessageDialog(
                    this,
                    resultado,
                    "Actualizacion exitosa",
                    javax.swing.JOptionPane.INFORMATION_MESSAGE
            );

            System.out.println("======================================");
            System.out.println(" PERFIL ACTUALIZADO");
            System.out.println(" Usuario: " + usuarioActual.getNombre()
                    + " " + usuarioActual.getApellido());
            System.out.println(" ID Usuario: " + usuarioActual.getIdUsuario());
            System.out.println("======================================");

        } else {

            javax.swing.JOptionPane.showMessageDialog(
                    this,
                    resultado,
                    "Error al actualizar",
                    javax.swing.JOptionPane.WARNING_MESSAGE
            );
        }
    }//GEN-LAST:event_btnActualizarActionPerformed

    private void btnCerrarSesionActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnCerrarSesionActionPerformed
            int opcion = javax.swing.JOptionPane.showConfirmDialog(
                this,
                "¿Está seguro de que desea cerrar sesión?",
                "Cerrar sesión",
                javax.swing.JOptionPane.YES_NO_OPTION,
                javax.swing.JOptionPane.QUESTION_MESSAGE
        );

        if (opcion == javax.swing.JOptionPane.YES_OPTION) {

            Login login = new Login();

            login.setLocationRelativeTo(null);
            login.setVisible(true);

            this.dispose();

            System.out.println("Sesión cerrada correctamente.");
        }
    }//GEN-LAST:event_btnCerrarSesionActionPerformed

    private void btnEliminarCuentaActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnEliminarCuentaActionPerformed
            int opcion = javax.swing.JOptionPane.showConfirmDialog(
                this,
                "¿Está seguro de que desea eliminar su cuenta?\n"
                + "Esta acción no se puede deshacer.",
                "Eliminar cuenta",
                javax.swing.JOptionPane.YES_NO_OPTION,
                javax.swing.JOptionPane.WARNING_MESSAGE
        );

        if (opcion == javax.swing.JOptionPane.YES_OPTION) {

            AutenticacionService servicio = new AutenticacionService();

            boolean eliminado = servicio.eliminarCuenta(usuarioActual);

            if (eliminado) {

                javax.swing.JOptionPane.showMessageDialog(
                        this,
                        "Su cuenta ha sido eliminada correctamente.",
                        "Cuenta eliminada",
                        javax.swing.JOptionPane.INFORMATION_MESSAGE
                );

                Login login = new Login();

                login.setLocationRelativeTo(null);
                login.setVisible(true);

                this.dispose();

            } else {

                javax.swing.JOptionPane.showMessageDialog(
                        this,
                        "No fue posible eliminar la cuenta.",
                        "Error",
                        javax.swing.JOptionPane.ERROR_MESSAGE
                );
            }
        }
    }//GEN-LAST:event_btnEliminarCuentaActionPerformed

